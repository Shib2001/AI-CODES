# Now explain vector embeddings
# Vector Embeddings in GenAI
# Definition: Vector embeddings are numerical representations of data, such as words, sentences, images, or documents, in the form of a list of numbers called a vector. These numbers capture patterns and relationships in the data so that AI systems can compare meaning and similarity.

# Let's understand this step by step.

# 1. What is a vector embedding?
# Suppose we have three words:

# Cat

# Dog

# Car

# An AI model converts each word into a vector of numbers.

# European shorthair cat with a curious expression on a white background

# Cat

# Example vector

# [0.82, 0.74, 0.12, 0.91]

# Golden retriever panting and looking happy on white background

# Dog

# Example vector

# [0.79, 0.71, 0.18, 0.87]

# «Гольфстрим» — автосервис в Мурманске: ремонт, ТО, шиномонтаж с гарантией

# Car

# Example vector

# [0.11, 0.23, 0.94, 0.16]

# These vectors are invented for illustration. Real embedding vectors often have hundreds or thousands of dimensions.

# Notice that the example vectors for cat and dog are similar, while the vector for car is different.

# This illustrates the main idea: data with similar meanings or characteristics can have similar embeddings, depending on what the model was trained to represent.